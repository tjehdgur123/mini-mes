-- 재실행용: 기존 테이블 삭제 (없으면 아무 일도 하지 않음)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'LOT_DEFECT','LOT_HISTORY','LOT_GENEALOGY','EQUIPMENT_EVENT',
      'LOT','WORK_ORDER','DEFECT_CODE','EQUIPMENT','ROUTING','PROCESS','ITEM'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. 기준정보 (Master Data)
-- ---------------------------------------------------------------------

-- 품목: 원자재(RAW) / 완제품(FG)
CREATE TABLE item (
  item_code   VARCHAR2(30)  CONSTRAINT pk_item PRIMARY KEY,
  item_name   VARCHAR2(100) NOT NULL,
  item_type   VARCHAR2(10)  NOT NULL CONSTRAINT ck_item_type CHECK (item_type IN ('RAW','FG')),
  spec        VARCHAR2(200),
  unit        VARCHAR2(10)  NOT NULL,
  use_yn      CHAR(1)       DEFAULT 'Y' NOT NULL CONSTRAINT ck_item_use CHECK (use_yn IN ('Y','N')),
  created_at  TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 공정
CREATE TABLE process (
  process_code  VARCHAR2(10)  CONSTRAINT pk_process PRIMARY KEY,
  process_name  VARCHAR2(50)  NOT NULL,
  description   VARCHAR2(200)
);

-- 라우팅: 품목별 공정 순서
CREATE TABLE routing (
  item_code     VARCHAR2(30) NOT NULL CONSTRAINT fk_routing_item REFERENCES item(item_code),
  seq           NUMBER(3)    NOT NULL,
  process_code  VARCHAR2(10) NOT NULL CONSTRAINT fk_routing_process REFERENCES process(process_code),
  CONSTRAINT pk_routing PRIMARY KEY (item_code, seq),
  CONSTRAINT uq_routing_process UNIQUE (item_code, process_code)
);

-- 설비
CREATE TABLE equipment (
  equipment_code  VARCHAR2(20)  CONSTRAINT pk_equipment PRIMARY KEY,
  equipment_name  VARCHAR2(100) NOT NULL,
  process_code    VARCHAR2(10)  NOT NULL CONSTRAINT fk_equipment_process REFERENCES process(process_code),
  status          VARCHAR2(10)  DEFAULT 'IDLE' NOT NULL
                  CONSTRAINT ck_equipment_status CHECK (status IN ('IDLE','RUN','DOWN','PM'))
);

-- 불량 코드
CREATE TABLE defect_code (
  defect_code   VARCHAR2(10)  CONSTRAINT pk_defect_code PRIMARY KEY,
  defect_name   VARCHAR2(50)  NOT NULL,
  process_code  VARCHAR2(10)  CONSTRAINT fk_defect_process REFERENCES process(process_code)
);

-- ---------------------------------------------------------------------
-- 2. 생산 (Production)
-- ---------------------------------------------------------------------

-- 작업지시
CREATE TABLE work_order (
  wo_no       VARCHAR2(30) CONSTRAINT pk_work_order PRIMARY KEY,
  item_code   VARCHAR2(30) NOT NULL CONSTRAINT fk_wo_item REFERENCES item(item_code),
  plan_qty    NUMBER(12)   NOT NULL CONSTRAINT ck_wo_qty CHECK (plan_qty > 0),
  due_date    DATE,
  status      VARCHAR2(15) DEFAULT 'CREATED' NOT NULL
              CONSTRAINT ck_wo_status CHECK (status IN ('CREATED','RELEASED','IN_PROGRESS','COMPLETED','CLOSED')),
  created_at  TIMESTAMP    DEFAULT LOCALTIMESTAMP NOT NULL
);

-- LOT: 생산 LOT과 원자재 LOT을 함께 관리
--   qty         : 현재 보유 수량 (마지막 Track-out 양품 수량, 분할된 부모 LOT은 0)
--   current_seq : 마지막으로 Track-in 한 공정 순번 (0 = 미착수, 원자재 LOT은 NULL)
--                 WAIT 상태면 다음 공정 = current_seq + 1
--   hold_reason : HOLD 사유 (자동 이상 감지 또는 수동 HOLD)
--   version     : 동시 수정 감지용 버전 번호 (갱신할 때마다 +1)
CREATE TABLE lot (
  lot_no       VARCHAR2(30)  CONSTRAINT pk_lot PRIMARY KEY,
  item_code    VARCHAR2(30)  NOT NULL CONSTRAINT fk_lot_item REFERENCES item(item_code),
  wo_no        VARCHAR2(30)  CONSTRAINT fk_lot_wo REFERENCES work_order(wo_no),
  qty          NUMBER(14,3)  NOT NULL CONSTRAINT ck_lot_qty CHECK (qty >= 0),
  current_seq  NUMBER(3),
  lot_status   VARCHAR2(10)  NOT NULL
               CONSTRAINT ck_lot_status CHECK (lot_status IN ('STOCK','WAIT','RUN','HOLD','FINISHED','SPLIT','SCRAPPED')),
  hold_reason  VARCHAR2(200),
  version      NUMBER(10)    DEFAULT 0 NOT NULL,
  created_at   TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  updated_at   TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 공정 이력 (Track-in / Track-out)
--   한 LOT은 같은 공정 순번을 한 번만 통과 (재작업은 범위 밖)
--   in_request_key / out_request_key : Track-in / Track-out 요청 멱등키
--                 설비/단말이 같은 요청을 재전송해도 한 번만 반영
CREATE TABLE lot_history (
  history_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)
                  CONSTRAINT pk_lot_history PRIMARY KEY,
  lot_no          VARCHAR2(30) NOT NULL CONSTRAINT fk_hist_lot REFERENCES lot(lot_no),
  seq             NUMBER(3)    NOT NULL,
  process_code    VARCHAR2(10) NOT NULL CONSTRAINT fk_hist_process REFERENCES process(process_code),
  equipment_code  VARCHAR2(20) NOT NULL CONSTRAINT fk_hist_equipment REFERENCES equipment(equipment_code),
  operator_id     VARCHAR2(20),
  in_qty          NUMBER(14,3) NOT NULL CONSTRAINT ck_hist_in CHECK (in_qty > 0),
  good_qty        NUMBER(14,3),
  defect_qty      NUMBER(14,3),
  track_in_at     TIMESTAMP    NOT NULL,
  track_out_at    TIMESTAMP,
  in_request_key  VARCHAR2(64) CONSTRAINT uq_hist_in_request UNIQUE,
  out_request_key VARCHAR2(64) CONSTRAINT uq_hist_out_request UNIQUE,
  CONSTRAINT uq_hist_lot_seq UNIQUE (lot_no, seq),
  -- 진행 중이면 수량 미확정, 완료면 양품+불량 = 투입
  CONSTRAINT ck_hist_qty CHECK (
       (track_out_at IS NULL AND good_qty IS NULL AND defect_qty IS NULL)
    OR (track_out_at IS NOT NULL AND good_qty >= 0 AND defect_qty >= 0
        AND good_qty + defect_qty = in_qty AND track_out_at >= track_in_at)
  )
);

-- 공정별 불량 상세
CREATE TABLE lot_defect (
  defect_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)
               CONSTRAINT pk_lot_defect PRIMARY KEY,
  history_id   NUMBER       NOT NULL CONSTRAINT fk_defect_hist REFERENCES lot_history(history_id),
  defect_code  VARCHAR2(10) NOT NULL CONSTRAINT fk_defect_code REFERENCES defect_code(defect_code),
  qty          NUMBER(14,3) NOT NULL CONSTRAINT ck_defect_qty CHECK (qty > 0),
  CONSTRAINT uq_defect_hist_code UNIQUE (history_id, defect_code)
);

-- ---------------------------------------------------------------------
-- 3. 추적 (Traceability)
-- ---------------------------------------------------------------------

-- LOT 계보: 원자재 투입(CONSUME), 분할(SPLIT), 병합(MERGE)
CREATE TABLE lot_genealogy (
  parent_lot_no  VARCHAR2(30) NOT NULL CONSTRAINT fk_gen_parent REFERENCES lot(lot_no),
  child_lot_no   VARCHAR2(30) NOT NULL CONSTRAINT fk_gen_child  REFERENCES lot(lot_no),
  relation_type  VARCHAR2(10) NOT NULL CONSTRAINT ck_gen_type CHECK (relation_type IN ('CONSUME','SPLIT','MERGE')),
  qty            NUMBER(14,3) NOT NULL CONSTRAINT ck_gen_qty CHECK (qty > 0),
  created_at     TIMESTAMP    DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT pk_lot_genealogy PRIMARY KEY (parent_lot_no, child_lot_no),
  CONSTRAINT ck_gen_self CHECK (parent_lot_no <> child_lot_no)
);

-- ---------------------------------------------------------------------
-- 4. 설비 이벤트
-- ---------------------------------------------------------------------
CREATE TABLE equipment_event (
  event_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)
                  CONSTRAINT pk_equipment_event PRIMARY KEY,
  equipment_code  VARCHAR2(20) NOT NULL CONSTRAINT fk_event_equipment REFERENCES equipment(equipment_code),
  status          VARCHAR2(10) NOT NULL CONSTRAINT ck_event_status CHECK (status IN ('IDLE','RUN','DOWN','PM')),
  started_at      TIMESTAMP    NOT NULL,
  ended_at        TIMESTAMP,
  reason          VARCHAR2(200),
  request_key     VARCHAR2(64) CONSTRAINT uq_event_request UNIQUE,      -- 비가동 시작 요청 멱등키
  end_request_key VARCHAR2(64) CONSTRAINT uq_event_end_request UNIQUE,  -- 복구(종료) 요청 멱등키
  CONSTRAINT ck_event_time CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- ---------------------------------------------------------------------
-- 5. 인덱스 (조회 패턴 기준)
-- ---------------------------------------------------------------------
CREATE INDEX ix_lot_wo            ON lot (wo_no);
CREATE INDEX ix_lot_status        ON lot (lot_status);
-- 설비별 실적 조회
CREATE INDEX ix_hist_equipment    ON lot_history (equipment_code, track_in_at);
-- 역방향 추적
CREATE INDEX ix_gen_child         ON lot_genealogy (child_lot_no);
-- 불량 파레토
CREATE INDEX ix_defect_code       ON lot_defect (defect_code);
CREATE INDEX ix_event_equipment   ON equipment_event (equipment_code, started_at);
